import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const softwareLicense = 'GPL-3.0-only';
const documentationLicense = 'CC-BY-SA-4.0';
const obsoleteSpdx = ['SPDX-License-Identifier:', 'Apache-2.0'].join(' ');

const metadata = JSON.parse(execFileSync('cargo', [
  'metadata', '--no-deps', '--format-version', '1',
], { cwd: root, encoding: 'utf8' }));
for (const pkg of metadata.packages) {
  assert.equal(pkg.license, softwareLicense, `${pkg.name} software license`);
}

for (const relativePath of [
  'LICENSE',
  'LICENSE-DOCUMENTATION',
  'LICENSES/GPL-3.0-only.txt',
  'LICENSES/CC-BY-SA-4.0.txt',
  'LICENSING.md',
]) {
  const absolute = path.join(root, relativePath);
  assert.ok(existsSync(absolute), `missing license contract file: ${relativePath}`);
  assert.ok(readFileSync(absolute).length > 0, `empty license contract file: ${relativePath}`);
}

const tracked = execFileSync('git', ['ls-files', '-z'], {
  cwd: root,
  encoding: 'utf8',
}).split('\0').filter(Boolean);
const generatedTemplates = new Set([
  'crates/pliego-starters/templates/default/src/main.rs',
  'crates/pliego-starters/templates/default/src/domain.rs',
  'crates/pliego-starters/templates/minimal/src/main.rs',
  'crates/pliego-starters/templates/editorial/src/main.rs',
  'crates/pliego-starters/templates/cinematic/src/main.rs',
]);

for (const relativePath of tracked) {
  if (!isTextSource(relativePath)) continue;
  const source = readFileSync(path.join(root, relativePath), 'utf8');
  assert.ok(
    !source.includes(obsoleteSpdx),
    `${relativePath} retains the obsolete Apache SPDX identifier`,
  );
  if (generatedTemplates.has(relativePath)) {
    assert.ok(
      source.startsWith('// Generated by PliegoRS. Choose a project license before distribution.'),
      `${relativePath} lacks the generated-project license notice`,
    );
  }
}

const licensing = readFileSync(path.join(root, 'LICENSING.md'), 'utf8');
for (const token of [softwareLicense, documentationLicense, 'v0.4.0-beta.1', 'Apache-2.0']) {
  assert.ok(licensing.includes(token), `LICENSING.md lacks ${token}`);
}

console.log(`License contract PASS: ${softwareLicense} software, ${documentationLicense} documentation/media`);

function isTextSource(relativePath) {
  return /(?:^|\/)(?:Cargo\.toml|[^/]+\.(?:css|html|js|json|md|mjs|ps1|py|rs|sh|toml|ts|tsx|wit|ya?ml))$/u
    .test(relativePath);
}
